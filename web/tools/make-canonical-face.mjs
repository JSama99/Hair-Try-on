// Convert MediaPipe's canonical_face_model.obj (cm) into web/src/canonical-face.js (m)
// and HairKit's test fixture. Run: node tools/make-canonical-face.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..', '..');
const obj = readFileSync(path.join(root, 'reference', 'data', 'canonical_face_model.obj'), 'utf8');
const v = [], f = [], uv = [];
for (const line of obj.split('\n')) {
  const t = line.trim().split(/\s+/);
  if (t[0] === 'v') v.push(t.slice(1, 4).map((x) => Math.round(Number(x) * 0.01 * 1e8) / 1e8));
  else if (t[0] === 'vt') uv.push(t.slice(1, 3).map(Number));
  else if (t[0] === 'f') f.push(t.slice(1, 4).map((x) => Number(x.split('/')[0]) - 1));
}
if (v.length !== 468 || f.length !== 898) throw new Error(`unexpected mesh ${v.length}/${f.length}`);

const header = `// Generated by tools/make-canonical-face.mjs from reference/data/canonical_face_model.obj.
// MediaPipe canonical face model, Copyright 2020 The MediaPipe Authors, Apache License 2.0
// (https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/).
// Converted from centimetres to metres; triangle indices are 0-based.\n`;
writeFileSync(path.join(root, 'web', 'src', 'canonical-face.js'),
  `${header}export const FACE_VERTICES = ${JSON.stringify(v)};\nexport const FACE_TRIANGLES = ${JSON.stringify(f)};\n`);

const fixtureDir = path.join(root, 'ios', 'Packages', 'HairKit', 'Tests', 'Fixtures');
mkdirSync(fixtureDir, { recursive: true });
writeFileSync(path.join(fixtureDir, 'canonical_face.json'),
  JSON.stringify({ source: 'MediaPipe canonical_face_model.obj (Apache-2.0), metres', vertices: v, triangles: f }) + '\n');
console.log(`wrote canonical-face.js and canonical_face.json (${v.length} vertices, ${f.length} triangles)`);
